// Builds dist/ from src/ (plain + minified JS/CSS), dist/plugin.apx (the APEXlang plug-in definition with the embedded
// PL/SQL from src/mediaplus.plsql) and db/mediaplus_pkg.sql. With APEX_APP_DIR set to an APEXlang application folder,
// the static files and plugin.apx are also written into it (shared-components/plugins/item/mediaPlus).
//   npm install && npm run build
import { build } from "esbuild";
import { mkdirSync, copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const VERSION = "2.0.0";
const APP = process.env.APEX_APP_DIR ? process.env.APEX_APP_DIR.replace(/[\\/]+$/, "") + "/shared-components/plugins/item/mediaPlus" : null;

mkdirSync("dist", { recursive: true });
copyFileSync("src/mediaPlus.js", "dist/mediaPlus.js");
copyFileSync("src/mediaPlus.css", "dist/mediaPlus.css");
await build({ entryPoints: ["src/mediaPlus.js"], outfile: "dist/mediaPlus.min.js", minify: true, charset: "ascii",
              legalComments: "inline", target: ["es2019", "chrome90", "firefox90", "safari14"] });
await build({ entryPoints: ["src/mediaPlus.css"], outfile: "dist/mediaPlus.min.css", minify: true, charset: "ascii",
              target: ["chrome111", "firefox113", "safari16.2"] });

for (const [dir, files] of [["js", ["mediaPlus.js", "mediaPlus.min.js"]], ["css", ["mediaPlus.css", "mediaPlus.min.css"]]]) {
    if (APP) { mkdirSync(`${APP}/static-files/${dir}`, { recursive: true }); }
    for (const f of files) {
        if (APP) { copyFileSync(`dist/${f}`, `${APP}/static-files/${dir}/${f}`); }
        console.log(f.padEnd(24), (readFileSync(`dist/${f}`).length / 1024).toFixed(1) + " KB");
    }
}

// plugin.apx: template + PL/SQL (indented into the fenced block)
const plsql = readFileSync("src/mediaplus.plsql", "utf8").replace(/\r\n/g, "\n").trimEnd();
if (plsql.length > 32767) { throw new Error(`PL/SQL is ${plsql.length} characters - the plug-in source holds 32767`); }
const indented = plsql.split("\n").map(l => (l ? "            " + l : "")).join("\n");
// file URLs carry a content hash, so browsers never keep an old copy after a rebuild
const hash = createHash("sha256").update(readFileSync("dist/mediaPlus.min.js")).update(readFileSync("dist/mediaPlus.min.css")).digest("hex").slice(0, 8);
const apx = readFileSync("plugin/plugin.template.apx", "utf8").replace(/\r\n/g, "\n")
    .replace("@@PLSQL@@", () => indented)   // a function, so "$'" in the PL/SQL is not a replacement pattern
    .replaceAll("?v=@@VERSION@@", `?v=${VERSION}-${hash}`)
    .replaceAll("@@VERSION@@", VERSION);
writeFileSync("dist/plugin.apx", apx);
if (APP) { writeFileSync(`${APP}/plugin.apx`, apx); }

// optional package with the same code, for production: compiled once instead of on every request
mkdirSync("db", { recursive: true });
const sig = {
    render: "p_item in apex_plugin.t_item, p_plugin in apex_plugin.t_plugin, p_param in apex_plugin.t_item_render_param, p_result in out nocopy apex_plugin.t_item_render_result",
    ajax: "p_item in apex_plugin.t_item, p_plugin in apex_plugin.t_plugin, p_param in apex_plugin.t_item_ajax_param, p_result in out nocopy apex_plugin.t_item_ajax_result",
    validation: "p_item in apex_plugin.t_item, p_plugin in apex_plugin.t_plugin, p_param in apex_plugin.t_item_validation_param, p_result in out nocopy apex_plugin.t_item_validation_result"
};
writeFileSync("db/mediaplus_pkg.sql",
    `-- MediaPlus ${VERSION} - optional package with the plug-in's PL/SQL (generated by build.mjs from src/mediaplus.plsql).\n` +
    `-- Install it in the parsing schema, then in the plug-in set Callbacks to MEDIAPLUS_PKG.RENDER / .AJAX / .VALIDATION\n` +
    `-- and empty Source > PL/SQL Code. Same behaviour, but compiled once instead of on every page view and upload request.\n` +
    `set define off\n\ncreate or replace package mediaplus_pkg as\n` +
    Object.entries(sig).map(([n, s]) => `    procedure ${n} (${s});\n`).join("") +
    `end mediaplus_pkg;\n/\n\ncreate or replace package body mediaplus_pkg as\n\n${plsql}\n\nend mediaplus_pkg;\n/\n`);
writeFileSync("dist/VERSION", VERSION + "\n");
console.log("plugin.apx".padEnd(24), `PL/SQL ${plsql.length} chars`);
